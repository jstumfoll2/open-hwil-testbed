"""Run a scenario on the compiled executive (executive/, binary ``hwil_exec``).

The binary does the frame loop (JSBSim + builtin controller + faults) and
writes log.csv, timing.csv and events.csv. Everything else (grading, plots,
manifest) is the same Python code used for the Python executive.

Find the binary with ``$HWIL_EXEC_BIN`` or ``executive/build/hwil_exec``.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import numpy as np

from . import models
from .executive import LOG_COLUMNS, TIMING_COLUMNS, TimingStats
from .manifest import sha256_file

REPO_ROOT = Path(__file__).resolve().parent.parent


class CppExecError(RuntimeError):
    pass


def binary() -> Path:
    env = os.environ.get("HWIL_EXEC_BIN")
    p = Path(env) if env else REPO_ROOT / "executive" / "build" / "hwil_exec"
    if not p.is_file():
        raise CppExecError(f"compiled executive not found at {p}; build it (see executive/README.md) "
                           "or set HWIL_EXEC_BIN")
    return p


def write_config(sc: dict, path: Path) -> None:
    if sc["vehicle"]["model"] not in models.OVERLAYS and not (models.jsbsim_root() / "aircraft" / sc["vehicle"]["model"]).is_dir():
        raise CppExecError(f"unknown model {sc['vehicle']['model']}")
    aircraft_path, model = models.prepare_aircraft(sc["vehicle"]["model"])
    init, wind, sim = sc["initial"], sc["wind"], sc["sim"]
    lines = [
        "# generated by hwil.cppexec from the resolved scenario",
        f"jsbsim_root {models.jsbsim_root()}",
        f"aircraft_path {aircraft_path}",
        f"model {model}",
        f"seed {int(sc['seed'])}",
        f"rate_hz {sim['rate_hz']!r}",
        f"duration_s {float(sim['duration_s'])!r}",
        f"stop_after_landed_s {float(sim['stop_after_landed_s'])!r}",
        f"lat_deg {float(init['lat_deg'])!r}",
        f"lon_deg {float(init['lon_deg'])!r}",
        f"ground_alt_msl_m {float(init['ground_alt_msl_m'])!r}",
        f"heading_deg {float(init['heading_deg'])!r}",
        f"wind_north_mps {float(wind['north_mps'])!r}",
        f"wind_east_mps {float(wind['east_mps'])!r}",
        f"wind_down_mps {float(wind['down_mps'])!r}",
        f"turbulence_severity {int(wind.get('turbulence_severity', 0))}",
    ]
    for ph in sc["mission"]:
        kv = " ".join(f"{k} {float(v)!r}" for k, v in ph.items() if k != "type")
        lines.append(f"phase {ph['type']} {kv}".rstrip())
    for f in sc["faults"]:
        kv = " ".join(f"{k} {float(v)!r}" for k, v in f.items() if k != "type")
        lines.append(f"fault {f['type']} {kv}".rstrip())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(sc: dict, opts: dict, run_dir: Path) -> tuple[dict, np.ndarray, np.ndarray, dict]:
    """Returns (results, log, timing_rows, controller_info)."""
    if opts["controller"] != "builtin":
        raise CppExecError("the compiled executive only runs the builtin controller so far")
    exe = binary()
    cfg = run_dir / "exec.cfg"
    write_config(sc, cfg)
    cmd = [str(exe), "--config", str(cfg), "--out", str(run_dir), "--clock", opts["clock"]]
    if opts.get("rt_priority") is not None:
        cmd += ["--rt-priority", str(opts["rt_priority"])]
    if opts.get("rt_cpu") is not None:
        cmd += ["--cpu", str(opts["rt_cpu"])]
    with open(run_dir / "exec_stdout.txt", "w") as out:
        proc = subprocess.run(cmd, stdout=out, stderr=subprocess.PIPE, text=True)
    if proc.returncode != 0:
        raise CppExecError(f"hwil_exec failed ({proc.returncode}): {proc.stderr.strip()}")

    log = np.loadtxt(run_dir / "log.csv", delimiter=",", skiprows=1, ndmin=2)
    with open(run_dir / "log.csv") as fh:
        if fh.readline().strip().split(",") != LOG_COLUMNS:
            raise CppExecError("hwil_exec log columns do not match hwil.executive.LOG_COLUMNS")
    tim = np.loadtxt(run_dir / "timing.csv", delimiter=",", skiprows=1, ndmin=2)
    summary = dict(line.split(" ", 1) for line in (run_dir / "exec_summary.txt").read_text().splitlines()
                   if " " in line)
    events = []
    for line in (run_dir / "events.csv").read_text().splitlines()[1:]:
        t, ph = line.split(",")
        events.append({"t": round(float(t), 4), "phase": ph})
    stats = TimingStats(period_us=1e6 / sc["sim"]["rate_hz"])
    stats.frames = len(tim)
    stats.overruns = int(tim[:, 5].sum()) if len(tim) else 0
    stats.late_us, stats.compute_us, stats.io_wait_us = tim[:, 2].tolist(), tim[:, 3].tolist(), tim[:, 4].tolist()
    aborted = summary.get("aborted", "").strip() or None
    results = {
        "sim_time_s": float(log[-1, 0]) if len(log) else 0.0,
        "wall_time_s": float(summary.get("wall_time_s", 0)),
        "mission_events": events,
        "landed": summary.get("landed", "0").strip() == "1",
        "aborted": aborted,
        "timing": stats.summary(),
        "realtime_setup": {"executive_notes": summary.get("rt_note", "").strip()},
    }
    info = {"controller": "builtin", "executive": "cpp", "binary": str(exe), "binary_sha256": sha256_file(exe)}
    assert len(TIMING_COLUMNS) == tim.shape[1]
    return results, log, tim, info
